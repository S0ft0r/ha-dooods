_LABEL_SEPARATOR = re.compile(r"[^a-z0-9]+")


def label_translation_key(label: str) -> str:
    """Вернуть ключ перевода для метки либо общий ключ для неизвестного класса."""
    normalized_label = _LABEL_SEPARATOR.sub("_", label.casefold()).strip("_")
    if normalized_label in SUPPORTED_LABEL_KEYS:
        return f"label_{normalized_label}"
    return "object"
